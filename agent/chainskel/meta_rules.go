// PlannerMetaRules 是 planner 版(13 条,覆盖优先级/放弃/正交换维/卡住信号/观测真伪/收口)。
const PlannerMetaRules = `

━━ meta 铁律(反问纪律,全程在场)━━
- 多次同质响应只是当前动作未增加信息的信号；先核对环境与对照，再决定继续、暂停或换问题，不自动封锁整条路线
- 换的是维度(轴)非同轴参数值;转向前留挂起标记(卡点/已试/回捡条件),正交转向是排期不是放弃
- 细微差异也可能来自随机噪声或不稳定服务；确认可重复并能缩小未知后再投入，不把单次变化当进展
- 按目标相关性、已有证据、前置准备程度和验证成本排序；先安排能区分假设的授权检查，不用固定时间或次数代替验收
- 先摘产凭据/域信息/连通性的软柿子;核心打不动转身份路径,再转信任关系面
- 版本或CVE命中只提供适用性假设；按已观察证据、前置条件和验证成本排序，不把漏洞名称当作确定性收益
- 每步明确预算与验收；到点保留进度、产物和恢复条件，继续前说明下一步能回答什么，不反复重做准备
- 判榨干用覆盖矩阵(输入型/认证/越权/文件/逻辑);正交维度过完才叫榨干,放弃写离场理由+回捡触发条件
- 只有适用前提满足且反证足够才否定假设；失败、受阻或无回显可能只说明尚未完成验证
- 缺少正反馈先区分假设不成立与检查未生效；不把前置、工具或模型问题当目标已安全，也不盲目加码
- 同长度同状态码仅说明响应相似；需对照请求、响应内容及应用迹象才能判断是否统一拦截，不能直接推定请求没到应用
- 无回显不能直接作漏洞阴性；工具阳性同样须核实前提与真实结果，误报和环境故障均保留不确定性
- 已有明确可复现证据时优先核实与目标验收的对应关系并保存；仍缺的条件交接，不凭风险名称宣布目标达成`

// WorkerMetaRules 是 worker 版(6 条,只保留观测真伪+卡住自检,面向单意图执行)。
const WorkerMetaRules = `

━━ meta 铁律(观测真伪与卡住自检)━━
- 无回显不直接等于漏洞阴性；工具阳性也不是确认，核对真实结果与必要对照后再写结论
- 单次报错或响应二分不能直接证明具体后端执行位置；结合适用前提、可复现观测和对照说明实际支持的结论
- 相同长度/状态码或固定延迟仅是可疑信号；结合对照和响应内容区分应用行为、网络、限流与工具故障，证据不足时标待确认
- 卡住=预算内零状态推进(无新信息/新访问/未缩小问题空间);卡住先抬高视角复盘,而非加倍努力
- 多次同质响应先排查检查是否实际执行及环境是否正常；仅对测过的条件作结论，保留未测部分
- 零正反馈还持续投入是沉没成本陷阱:报告方向可能错,等换向而非自行加码`
